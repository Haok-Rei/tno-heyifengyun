"""Export the approved v2 paintings for web panels; preserve transparency and provenance.

Composition originals remain untouched in route-art-v2/masters. This export only
trims invisible margins and makes small, browser-friendly derivatives.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'src/assets/route-art-v2'
OUTPUT = ROOT / 'src/assets/campaign-art'
receipt = []
registries = {}

for key, folder, target, size in [
    ('HERO_ART', 'masters/hero', 'subjects', (960, 840)),
    ('MECHANISM_ART', 'auxiliary', 'mechanisms', (160, 144)),
    ('BADGE_BACKDROP_ART', 'masters/backgrounds', 'frames', (240, 180)),
]:
    entries = []
    (OUTPUT / target).mkdir(parents=True, exist_ok=True)
    for source in sorted((SOURCE / folder).glob('*.png')):
        image = Image.open(source).convert('RGBA')
        if target == 'subjects':
            bounds = image.getchannel('A').point(lambda a: 255 if a >= 16 else 0).getbbox()
            if bounds:
                image = image.crop(bounds)
        image.thumbnail(size, Image.Resampling.LANCZOS)
        name = source.stem.removeprefix('H_')
        output = OUTPUT / target / (name + '.webp')
        temporary=output.with_suffix('.webp.tmp')
        image.save(temporary, 'WEBP', quality=92, method=6)
        temporary.replace(output)
        entries.append(f'  {json.dumps(name)}: new URL("../assets/campaign-art/{target}/{name}.webp", import.meta.url).href,')
        receipt.append({
            'source': source.relative_to(ROOT).as_posix(),
            'sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
            'output': output.relative_to(ROOT).as_posix(),
            'width': image.width, 'height': image.height, 'bytes': output.stat().st_size,
        })
    registries[key] = entries

lines = ['// Generated by scripts/art/build_campaign_art.py; original paintings are retained.']
for key, entries in registries.items():
    lines += [f'export const {key}: Record<string, string> = {{', *entries, '};', '']
(ROOT / 'src/config/campaignArtwork.ts').write_text('\n'.join(lines), encoding='utf-8')
(OUTPUT / 'receipts.json').write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
print(f'Exported {len(receipt)} assets, {sum(item["bytes"] for item in receipt):,} bytes.')
